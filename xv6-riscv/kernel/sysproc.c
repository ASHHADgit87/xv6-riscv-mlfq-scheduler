uint64
sys_exit(void)
{
  int n;
  argint(0, &n);
  kexit(n);
  return 0; // not reached
}

uint64
sys_getpid(void)
{
  return myproc()->pid;
}

uint64
sys_fork(void)
{
  return kfork();
}

uint64
sys_wait(void)
{
  uint64 p;
  argaddr(0, &p);
  return kwait(p);
}

uint64
sys_sbrk(void)
{
  uint64 addr;
  int t;
  int n;

  argint(0, &n);
  argint(1, &t);
  addr = myproc()->sz;

  if (t == SBRK_EAGER || n < 0) {
    if (growproc(n) < 0) {
      return -1;
    }
  } else {
    // Lazily allocate memory for this process: increase its memory
    // size but don't allocate memory. If the processes uses the
    // memory, vmfault() will allocate it.
    if (addr + n < addr)
      return -1;
    if (addr + n > TRAPFRAME)
      return -1;
    myproc()->sz += n;
  }
  return addr;
}

uint64
sys_pause(void)
{
  int n;
  uint ticks0;

  argint(0, &n);
  if (n < 0)
    n = 0;
  acquire(&tickslock);
  ticks0 = ticks;
  while (ticks - ticks0 < n) {
    if (killed(myproc())) {
      release(&tickslock);
      return -1;
    }
    sleep_prepare(&ticks);
    release(&tickslock);
    sleep();
    acquire(&tickslock);
  }
  release(&tickslock);
  return 0;
}

uint64
sys_kill(void)
{
  int pid;

  argint(0, &pid);
  return kkill(pid);
}

// return how many clock tick interrupts have occurred
// since start.
uint64
sys_uptime(void)
{
  uint xticks;

  acquire(&tickslock);
  xticks = ticks;
  release(&tickslock);
  return xticks;
}

// int getprocinfo(int pid, struct procinfo *info)
// pid <= 0 means "the calling process". Returns 0 on success, -1 on error.
// xv6 syscalls return a single int, so the metrics come back through *info.
uint64
sys_getprocinfo(void)
{
  int pid;
  uint64 uaddr;
  struct procinfo info;
  struct proc *me = myproc();

  argint(0, &pid);
  argaddr(1, &uaddr);
  if (pid <= 0)
    pid = me->pid;

  // Snapshot under the target's lock, copy to user space after releasing it
  // (copyout must not run while holding a spinlock).
  if (kgetprocinfo(pid, &info) < 0)
    return -1;
  if (copyout(me->pagetable, me->sz, uaddr, (char *)&info, sizeof(info)) < 0)
    return -1;
  return 0;
}
